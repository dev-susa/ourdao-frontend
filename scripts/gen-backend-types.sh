#!/usr/bin/env bash
# Generates src/lib/generated/backend-api.ts from the ourdao-backend OpenAPI spec
# committed at src/lib/generated/backend-openapi.json (issue #343).
#
#   npm run gen:backend           # regenerate after updating the spec
#   npm run gen:backend -- --check  # fail if the committed output is stale (CI)
#
# To update the spec, copy the root openapi.json of ourdao-backend at the commit
# you target into src/lib/generated/backend-openapi.json, then regenerate and
# fix any type errors `tsc` reports in src/lib/backend.ts.
set -euo pipefail

spec="src/lib/generated/backend-openapi.json"
out="src/lib/generated/backend-api.ts"
check=false
if [[ "${1:-}" == "--check" ]]; then
  check=true
fi

tmp_dir="$(mktemp -d)"
trap 'rm -rf "$tmp_dir"' EXIT
generated="$tmp_dir/backend-api.ts"

{
  echo "// @generated by scripts/gen-backend-types.sh from ${spec} — do not edit by hand."
  echo "// Source: ourdao-backend openapi.json (OurDAO Backend API 0.2.0)"
  # Pinned and fetched on demand, so package-lock.json stays untouched (the lockfile
  # has an unrelated eslint peer conflict that blocks a clean regeneration).
  npx --yes openapi-typescript@7.13.0 "$spec" --export-type false
} > "$generated"

if [[ "$check" == true ]]; then
  if ! diff -u "$out" "$generated"; then
    echo "error: $out is stale. Run: npm run gen:backend" >&2
    exit 1
  fi
  echo "$out is up to date"
else
  cp "$generated" "$out"
  echo "wrote $out"
fi
